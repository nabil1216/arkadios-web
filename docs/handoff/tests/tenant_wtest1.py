    pg.goto(B + 'firms.html?view=v-onboarding'); pg.wait_for_timeout(400); ok('sidebar saved view link works', pg.locator('tr[data-row]').count() == 1)

    # ---------- global search ----------
    pg.goto(B + 'index.html'); pg.wait_for_timeout(300)
