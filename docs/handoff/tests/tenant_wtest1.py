import re
from playwright.sync_api import sync_playwright
B = 'http://127.0.0.1:8801/'
results = []
def ok(name, cond):
    results.append((name, bool(cond))); print(('PASS ' if cond else 'FAIL ') + name)

def login(pg, email):
    pg.goto(B + 'login.html'); pg.wait_for_timeout(250)
    pg.fill('#lg-email', email); pg.fill('#lg-pass', 'demo-1234')
    pg.get_by_role('button', name='Sign in', exact=True).click(); pg.wait_for_load_state(); pg.wait_for_timeout(450)

