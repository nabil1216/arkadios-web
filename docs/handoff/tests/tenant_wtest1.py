    br = p.chromium.launch()
    ctx = br.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
    pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append('pageerror: ' + str(e)))
    pg.on('console', lambda m: errs.append('console: ' + m.text) if m.type == 'error' else None)

    # ---------- sign in ----------
    pg.goto(B + 'tasks.html'); pg.wait_for_load_state(); pg.wait_for_timeout(300)
    ok('signed-out visit goes to sign in with the page to return to', 'login.html' in pg.url and 'next=tasks.html' in pg.url)
    pg.fill('#lg-email', 'nobody@arkadios.example'); pg.fill('#lg-pass', 'demo-1234'); pg.get_by_role('button', name='Sign in', exact=True).click()
    ok('unknown email rejected', 'not right' in pg.locator('#lg-pass-err').inner_text())
    pg.get_by_role('button', name=re.compile('Use this account.*Manager')).click(); pg.wait_for_timeout(200)
    ok('demo card fills the form', pg.input_value('#lg-email') == 'dana.reyes@arkadios.example' and pg.input_value('#lg-pass') == 'demo-1234')
    pg.get_by_role('button', name='Sign in', exact=True).click(); pg.wait_for_load_state(); pg.wait_for_timeout(400)
    ok('sign in returns to the requested page', pg.url.endswith('tasks.html'))
    pg.get_by_role('link', name='Forgot password?') if False else None
    pg.locator('#sign-out').click(); pg.wait_for_load_state(); pg.wait_for_timeout(300)
    ok('sign out goes to sign in', pg.url.endswith('login.html'))
    pg.get_by_role('link', name='Forgot password?').click(); pg.wait_for_timeout(250)
    pg.fill('#fp-email', 'bad'); pg.locator('#fp-form button[type=submit]').click()
    ok('forgot password validates', pg.locator('#fp-email-err:not([hidden])').count() == 1)
    pg.keyboard.press('Escape')

    login(pg, 'dana.reyes@arkadios.example')
    ok('manager lands on Command Center', pg.url.endswith('index.html'))
    ok('manager sees 7 menus', pg.locator('.side__link').count() == 7)
    ok('sidebar shows role', 'Manager' in pg.locator('.side__scope').inner_text())

    # ---------- Command Center ----------
    ok('greeting counts my tasks', '3 tasks need you today' in pg.locator('#main').inner_text() and '1 of them is overdue' in pg.locator('#main').inner_text())
    n0 = pg.locator('[data-card="due"] .rows__item').count()
    pg.locator('[data-scope="all"]').click(); pg.wait_for_timeout(200)
    ok('All scope shows more tasks', pg.locator('[data-card="due"] .rows__item').count() > n0)
    pg.locator('[data-scope="mine"]').click(); pg.wait_for_timeout(200)
    pg.locator('[data-done]').nth(1).click(); pg.wait_for_timeout(300)
    ok('checking a task completes it', '2 tasks need you today' in pg.locator('#main').inner_text())
    pg.get_by_role('link', name=re.compile('Show all')).click(); pg.wait_for_load_state(); pg.wait_for_timeout(300)
    ok('Show all links to tasks', pg.url.endswith('tasks.html?scope=mine'))
    pg.goto(B + 'index.html'); pg.wait_for_timeout(300)
    pg.get_by_role('link', name=re.compile('^Relationship Ops')).first.click(); pg.wait_for_load_state(); pg.wait_for_timeout(300)
    ok('overdue bar opens filtered tasks', 'dept=Relationship' in pg.url and 'due=overdue' in pg.url)
    pg.goto(B + 'index.html'); pg.wait_for_timeout(300)
    pg.get_by_role('link', name='Open board').click(); pg.wait_for_load_state(); ok('Open board link', pg.url.endswith('pipeline.html'))
    pg.goto(B + 'index.html'); pg.wait_for_timeout(300)
    pg.get_by_role('link', name='Northgate Partners').click(); pg.wait_for_load_state(); ok('queue link opens the firm', 'firm.html?id=f9' in pg.url)
    # edit layout
    pg.goto(B + 'index.html'); pg.wait_for_timeout(300)
    pg.locator('#h-edit').click(); pg.wait_for_timeout(200)
    ok('edit mode shows card controls', pg.locator('[data-mv="hide"]').count() == 5)
    pg.locator('[data-mv="hide"][data-card="notes"]').click(); pg.wait_for_timeout(200)
    ok('hidden card is removed', pg.locator('section[data-card="notes"]').count() == 0 and pg.locator('[data-show="notes"]').count() == 1)
    pg.locator('[data-mv="side"][data-card="pipeline"]').click(); pg.wait_for_timeout(200)
    ok('card moves to the other column', pg.locator('.col').first.locator('section[data-card="pipeline"]').count() == 1)
    pg.locator('[data-mv="up"][data-card="pipeline"]').click(); pg.wait_for_timeout(200)
    pg.locator('#h-edit').click(); pg.wait_for_timeout(200)
    pg.locator('#h-default').click(); ok('set as default toast', 'default view' in pg.locator('#toast').inner_text())
