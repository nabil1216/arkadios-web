    pg.locator('#bell').click(); pg.wait_for_load_state(); pg.wait_for_timeout(400); ok('bell opens the notifications page with overdue work', 'notifications.html' in pg.url and 'overdue' in pg.locator('#main').inner_text())

    print('ERRORS:', errs)
    failed = [n for n, c in results if not c]
    print('TOTAL', len(results), 'FAILED', len(failed), failed)
    br.close()
