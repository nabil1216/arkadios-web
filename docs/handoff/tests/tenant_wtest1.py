    pg.fill('#f-q', 'Dorothy Hargrove'); pg.wait_for_timeout(250); ok('search finds a firm by advisor name', pg.locator('tr[data-row]').count() == 1 and 'Cedarline' in pg.locator('tr[data-row]').inner_text())
    pg.fill('#f-q', 'LA-'); pg.wait_for_timeout(250); ok('search by rep code prefix', pg.locator('tr[data-row]').count() == 1)
    pg.fill('#f-q', 'Series 63'); pg.wait_for_timeout(250); ok('search by license', pg.locator('tr[data-row]').count() >= 1)
    pg.locator('#f-clear').click(); pg.wait_for_timeout(300)
    pg.select_option('#f-stage', '3'); pg.wait_for_timeout(250); ok('stage filter', pg.locator('tr[data-row]').count() == 5)
    pg.select_option('#f-state', 'AL'); pg.wait_for_timeout(250); ok('state filter combines', pg.locator('tr[data-row]').count() == 1)
    pg.locator('#f-clear').click(); pg.wait_for_timeout(300)
    pg.select_option('#f-lic', 'Series 63'); pg.wait_for_timeout(250); ok('license filter', 0 < pg.locator('tr[data-row]').count() < 17)
    pg.locator('#f-clear').click(); pg.wait_for_timeout(300)
    pg.locator('[data-view="v-onboarding"]').click(); pg.wait_for_timeout(250); ok('Onboarding queue view', pg.locator('tr[data-row]').count() == 1)
    pg.locator('[data-view="v-prospect"]').click(); pg.wait_for_timeout(250); ok('Prospect bench view', pg.locator('tr[data-row]').count() == 4)
    pg.locator('[data-view="v-overdue"]').click(); pg.wait_for_timeout(250); ok('Overdue, mine view', pg.locator('tr[data-row]').count() == 1 and 'Cedarline' in pg.locator('tr[data-row]').inner_text())
    pg.locator('[data-view="all"]').click(); pg.wait_for_timeout(250)
    pg.locator('[data-sort="name"]').click(); pg.wait_for_timeout(250)
    ok('sort descending by name', 'Vantage' in pg.locator('tr[data-row]').first.inner_text())
    pg.locator('tr[data-row]').nth(2).click(); pg.wait_for_timeout(250)
    ok('row click updates quick view', pg.locator('tr.is-sel').count() == 1 and pg.locator('.quick__name').inner_text() in pg.locator('tr.is-sel').inner_text())
    pg.locator('#q-note').click(); pg.wait_for_timeout(250); pg.fill('#ln-text', 'Checked rep codes with the firm.'); pg.locator('#ln-form button[type=submit]').click(); pg.wait_for_timeout(300)
