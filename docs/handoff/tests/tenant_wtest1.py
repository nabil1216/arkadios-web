    ok('layout persists after reload', pg.locator('section[data-card="notes"]').count() == 0 and pg.locator('.col').first.locator('section[data-card="pipeline"]').count() == 1)
    pg.locator('#h-edit').click(); pg.locator('[data-show="notes"]').click(); pg.wait_for_timeout(250)
    ok('hidden card can be added back', pg.locator('section[data-card="notes"]').count() == 1)
    pg.locator('#h-reset').click(); pg.wait_for_timeout(300)
    ok('reset layout returns to my saved default', pg.locator('section[data-card="notes"]').count() == 0 and pg.locator('.col').first.locator('section[data-card="pipeline"]').count() == 1)
    pg.locator('#h-edit').click()
    # new firm
    pg.locator('#h-new').click(); pg.wait_for_timeout(250)
    pg.locator('#nf-form button[type=submit]').click(); ok('new firm validates', pg.locator('dialog[open] .error:not([hidden])').count() == 3)
    pg.fill('#nf-name', 'Ashford Family Office'); pg.fill('#nf-city', 'Austin'); pg.fill('#nf-state', 'tx'); pg.locator('#nf-form button[type=submit]').click()
    ok('duplicate firm name blocked', 'already exists' in pg.locator('#nf-name-err').inner_text())
    pg.fill('#nf-name', 'Bluebonnet Advisors'); pg.locator('#nf-form button[type=submit]').click(); pg.wait_for_load_state(); pg.wait_for_timeout(500)
    ok('new firm opens in Prospect with a 5-step checklist', 'Bluebonnet Advisors' in pg.locator('h1').inner_text() and 'Prospect' in pg.locator('.firm-title').inner_text())
    pg.locator('[data-tab="tasks"]').click(); pg.wait_for_timeout(250)
    ok('prospect checklist tasks were created', pg.locator('.rows__item').count() == 5)

    # ---------- Firms ----------
    pg.goto(B + 'firms.html'); pg.wait_for_timeout(500)
    ok('17 firms after adding one', '17 firms' in pg.locator('.page__head').inner_text())
    ok('page 1 has 10 rows', pg.locator('tr[data-row]').count() == 10)
